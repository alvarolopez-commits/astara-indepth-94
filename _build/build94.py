"""Builds index_94.html (and index.html) from the files in _build/.
Usage (from the project folder):  python -X utf8 _build/build94.py _build .          (add --check to validate the catalogs and write nothing)

Sources: body94.html (page structure, no text), i18n/en.json + i18n/es.json (all text, by stable key), the docx (paras94.json),
the Excel (data94.json), style94.css, app94.js. The output is generated: edit the sources, never the html.
Stops (exit code 1, nothing written) if a key is missing, duplicated or unused, if a translation drops a placeholder or tag,
if a docx block is missing, duplicated or altered beyond the edits listed in EDITS, or if the docx and the Excel disagree."""
import json, sys, re, html as H
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import i18n_lib as I18

S, PROJ = sys.argv[1], sys.argv[2]
read = lambda name: open(f"{S}/{name}", encoding="utf-8").read()

HEAD = """<!DOCTYPE html>
<!-- GENERATED by _build/build94.py from _build/body94.html, _build/i18n/*.json, the docx and the Excel. Do not edit this file: changes are lost on the next build. -->
<html lang="en"><head>
<meta charset="UTF-8">
<meta name="viewport" content="width=device-width, initial-scale=1.0">
<title>{{TITLE}}</title>
<meta name="description" content="{{DESCRIPTION}}">
<meta name="theme-color" content="#221E41">
<link rel="preconnect" href="https://fonts.googleapis.com">
<link rel="preconnect" href="https://fonts.gstatic.com" crossorigin>
<link href="https://fonts.googleapis.com/css2?family=Orbitron:wght@500;600;700&family=Inter:wght@400;500;600;700&display=swap" rel="stylesheet">
<link rel="preload" as="image" href="deploy/img/hero94-1672.webp" imagesrcset="deploy/img/hero94-840.webp 840w, deploy/img/hero94-1672.webp 1672w" imagesizes="100vw">
<style>
"""

DATA = json.load(open(f"{S}/data94.json", encoding="utf-8"))
css, template = read("style94.css"), read("body94.html")
COLOR = json.load(open(f"{S}/color94.json", encoding="utf-8"))          # colour tokens decided by _build/color_decisions94.js (Color Intelligence Engine)
assert css.count("/*__COLOR_TOKENS__*/") == 1, "style94.css needs the colour placeholder"
css = css.replace("/*__COLOR_TOKENS__*/", COLOR["css"])
stale = sorted(set(re.findall(r"var\(--(h-[a-z]+|up|down|hatch-bus|hatch-car|hatch-down)\)", css + template + read("app94.js"))))
assert not stale, f"old colour tokens still used: {stale}"
P = json.load(open(f"{S}/paras94.json", encoding="utf-8"))
raw = dict(P["paras"])
e = I18.esc
norm = lambda s: re.sub(r"\s+", " ", H.unescape(re.sub(r"<[^>]+>", " ", s))).strip()
fail = []

# ---- editorial edits on top of the docx text: every one must apply exactly once ----
# [EXT: ...] and [DB + EXT: ...] markers are source tags for the editor; the sources go to captions and the Sources list.
TAG = re.compile(r" ?\[(?:DB \+ )?EXT(?:: [^\]]*)?\]")
RAW_EDITS = [   # references to the editor's files and marks, which are not published (applied before the tags are removed)
    ("how2", "[EXT] is an external source, with its URL in Appendix B and in the Excel. [DB] is an entry in the AllMoving database, with its id and URL in the 12_Entries_DB sheet. [Own calculation] is arithmetic",
             "every figure's source is listed with its URL at the end of the page. “Own calculation” marks arithmetic"),
    ("how3", " What could not be checked is in Appendix C, not in the text.", ""),
]
for k, old, new in RAW_EDITS:
    assert raw[k].count(old) == 1, (k, old)
    raw[k] = raw[k].replace(old, new)
paras = {k: TAG.sub("", v) for k, v in raw.items()}
n_tags = sum(len(TAG.findall(v)) for v in raw.values())
print(f"edits: {n_tags} source tags removed; {len(RAW_EDITS)} text edits")
paras["cover_sub"] = P["cover"][0]          # the cover strapline
BLOCKS = [k for k in paras if not k.startswith("src") and not k.endswith("_h")]
for k in BLOCKS: assert "[" not in paras[k], (k, paras[k])

ICONS = {   # 24x24 line icons (How to read cards)
    "scope": '<svg viewBox="0 0 24 24"><circle cx="12" cy="12" r="8.5"/><circle cx="12" cy="12" r="3.5"/><path d="M12 1.5v4M12 18.5v4M1.5 12h4M18.5 12h4"/></svg>',
    "tag": '<svg viewBox="0 0 24 24"><path d="M3 12.5V4h8.5L21 13.5 13.5 21Z"/><circle cx="7.5" cy="8.5" r="1.4"/></svg>',
    "check": '<svg viewBox="0 0 24 24"><path d="M6 3h9l4 4v14H6Z"/><path d="M9.5 13.5l2 2 3.5-4"/></svg>',
    "alert": '<svg viewBox="0 0 24 24"><path d="M12 3 2.5 20h19Z"/><path d="M12 10v5M12 17.6v.4"/></svg>',
}
body = template
for k, v in ICONS.items(): body = body.replace(f"[[ICON:{k}]]", v)

# ---- English that does not live in en.json: the docx tables (tbl.*) and the Excel labels (xl.*) ----
generated_en = {f"doc.{k}": paras[k] for k in BLOCKS}
generated_en.update(DATA["xl"])

def table(section, header):
    ts = [t for t in P["tables"] if t["section"] == section and t["rows"][0][:len(header)] == header]
    assert len(ts) == 1, (section, header, len(ts))
    return ts[0]["rows"][1:]

# V01 key figures: the docx table; the big number and its unit are the two parts of the "Value" cell. The Excel carries the same figures (cross-check).
KF_CLS = ["car", "car", "station", "price", "truck", "truck"]
kf = table("sum", ["Figure", "Value", "Date", "Context"])
assert len(kf) == 6 == len(DATA["kf"])
tiles = ""
for i, ((fig, val, date, ctx), x) in enumerate(zip(kf, DATA["kf"]), 1):
    m = re.match(r"^(\S+) (.+)$", val); assert m, val
    num, unit = m.groups()
    if x["figure"] != fig: fail.append(f"key figure {i}: docx {fig!r} vs Excel {x['figure']!r}")
    if float(num.replace(",", "")) != x["value"]: fail.append(f"key figure {i}: docx {num} vs Excel {x['value']}")
    generated_en.update({f"tbl.kf.{i}.fig": fig, f"tbl.kf.{i}.num": num, f"tbl.kf.{i}.unit": unit, f"tbl.kf.{i}.date": date, f"tbl.kf.{i}.ctx": ctx})
    tiles += (f'<div class="kfig__c kfig__c--{KF_CLS[i-1]}"><div class="kfig__v"><span data-i18n="tbl.kf.{i}.num"></span><small data-i18n="tbl.kf.{i}.unit"></small></div>'
              f'<div class="kfig__l" data-i18n="tbl.kf.{i}.fig"></div>'
              f'<div class="kfig__s"><span data-i18n="tbl.kf.{i}.date"></span> · <span data-i18n="tbl.kf.{i}.ctx"></span></div></div>')
body = body.replace("[[KEY_FIGURES]]", f'<div class="kfig">{tiles}</div>')

# Who is who: the docx table (the "Excel facts" column is the editor's and is not published)
who = table("who", ["Company", "What it has done", "Excel facts"])
assert len(who) == 12
# flag tiles (deploy/flags, flag-icons 1x1, MIT): the country of the company; the alliance of four companies has none
WHO_FLAGS = {"Daimler Truck": ["de"], "Toyota": ["jp"], "Hyundai": ["kr"], "General Motors and Honda": ["us", "jp"], "BMW": ["de"], "Air Liquide": ["fr"],
             "H2 Mobility (Germany)": ["de"], "Rhenus": ["de"], "Quantron": ["de"], "Arthur Bus": ["pl"], "Element 2": ["gb"]}
for n in WHO_FLAGS: assert n in [w[0] for w in who], n
flag_tile = lambda c: f'<span class="flag" style="background-image:url(deploy/flags/{c}.svg)" aria-hidden="true"></span>'
cards = ""
for i, (name, text, _facts) in enumerate(who, 1):
    generated_en.update({f"tbl.who.{i}.name": name, f"tbl.who.{i}.text": text})
    fl = f'<span class="flags">{"".join(flag_tile(c) for c in WHO_FLAGS[name])}</span>' if name in WHO_FLAGS else ""
    cards += f'<article class="who__c reveal"><div class="who__h">{fl}<h3 data-i18n="tbl.who.{i}.name"></h3></div><p data-i18n="tbl.who.{i}.text"></p></article>'
body = body.replace("[[WHO]]", f'<div class="who">{cards}</div>')

# What to watch: the docx table
watch = table("watch", ["Signal", "Why it matters", "When"])
assert len(watch) == 7
items = ""
for i, (signal, why, when) in enumerate(watch, 1):
    generated_en.update({f"tbl.watch.{i}.signal": signal, f"tbl.watch.{i}.why": why, f"tbl.watch.{i}.when": when})
    items += (f'<li class="wl__i reveal"><div class="wl__when" data-i18n="tbl.watch.{i}.when"></div><div class="wl__b"><div class="wl__sig" data-i18n="tbl.watch.{i}.signal"></div>'
              f'<p class="wl__why" data-i18n="tbl.watch.{i}.why"></p></div></li>')
body = body.replace("[[WATCH]]", f'<ol class="wl">{items}</ol>')

# ---- Sources (Appendix B): kept as published, in English. Lines without a URL are internal; a URL listed twice is shown once. ----
srcs, seen = [], set()
for k in sorted((k for k in paras if k.startswith("src")), key=lambda k: int(k[3:])):
    t = paras[k]
    if not re.search(r"\. https?://\S+$", t): continue          # internal file references (editor's workbook)
    m = re.match(r"^(.*?)(?: \(([^()]*(?:\([^()]*\)[^()]*)*)\))?\. (https?://\S+)$", t); assert m, t
    name, date, url = m.groups()
    if url in seen: continue
    seen.add(url)
    dom = re.sub(r"^www\d*\.", "", url.split("/")[2])
    srcs.append(f'<li>{e(name)}{f" <small>({e(date)})</small>" if date else ""} · <a href="{H.escape(url)}" target="_blank" rel="noopener">{e(dom)}</a></li>')
body = body.replace("[[SOURCES]]", '<ol lang="en">' + "".join(srcs) + "</ol>").replace("[[SOURCES_COUNT]]", str(len(srcs)))
assert "{{" not in body and "[[" not in body

# ---- catalogs, and the checks that stop the build ----
en_src, dup_en = I18.load_catalog(f"{S}/i18n/en.json")
es, dup_es = I18.load_catalog(f"{S}/i18n/es.json")
errors = [f"duplicate key in en.json: {k}" for k in dup_en] + [f"duplicate key in es.json: {k}" for k in dup_es]
try:
    en = I18.merge(en_src, generated_en)
except I18.CatalogError as x:
    errors.append(str(x)); en = {**en_src, **generated_en}
used, called = I18.scan_references(template + body, [read("app94.js"), Path(__file__).read_text(encoding="utf-8")])
plain_calls = set(re.findall(r"""\btp\(\s*['"]([^'"]+)['"]""", read("app94.js")))
v_err, v_warn = I18.validate(en, es, used, called, I18.attr_keys_in(body) | plain_calls)
errors += v_err + fail
if errors:
    print(f"CHECK FAILED ({len(errors)} errors):")
    for x in errors: print("  -", x)
    sys.exit(1)
for w in v_warn: print("i18n warning:", w)
print(f"i18n: {len(en)} keys in EN and ES; {len(v_warn)} warnings")
if "--check" in sys.argv: sys.exit(0)      # validate the catalogs only

# ---- fill the English the page ships with (the browser re-writes it in the chosen language) ----
count = {"filled": 0}
def fill(m):
    tag, attrs, key = m.group(1), m.group(2), m.group(3)
    args = json.loads(H.unescape(re.search(r"data-i18n-args='([^']*)'", attrs).group(1))) if "data-i18n-args=" in attrs else None
    fm = re.search(r'data-i18n-fmt="(\w+)"', attrs)
    count["filled"] += 1
    return f"<{tag}{attrs}>{I18.render(en, key, args, fm.group(1) if fm else None)}</{tag}>"
body = re.sub(r'<(\w+)(\s[^>]*?\bdata-i18n="([^"]+)"[^>]*)>(?=</\1>)</\1>', fill, body)
n_marked = len(re.findall(r'\bdata-i18n="', body))
if count["filled"] != n_marked: fail.append(f"{n_marked - count['filled']} data-i18n elements are not empty in the template (they must hold no text)")
def fill_attrs(m):
    tag = m.group(0)
    for part in re.search(r'data-i18n-attr="([^"]+)"', tag).group(1).split(";"):
        a, k = part.split(":", 1)
        tag, n = re.subn(rf'(\s{re.escape(a)}=)""', lambda x: f'{x.group(1)}"{H.escape(en[k])}"', tag, count=1)
        if not n: fail.append(f"data-i18n-attr {a}:{k}: the element needs an empty {a}=\"\" to fill")
    return tag
body = re.sub(r"<[^>]*\bdata-i18n-attr=\"[^\"]+\"[^>]*>", fill_attrs, body)

page = HEAD.replace("{{TITLE}}", H.escape(en["meta.title"])).replace("{{DESCRIPTION}}", H.escape(en["meta.description"])) + css + "</style>\n</head>\n<body>\n\n" + body
js = read("app94.js").replace("/*__DATA__*/null", read("data94.json")).replace("/*__I18N__*/null", json.dumps({"en": en, "es": es}, ensure_ascii=False, separators=(",", ":")).replace("</", "<\\/"))
page += '\n<script>\n' + js + "\n</script>\n\n</body></html>\n"

# ---- verification: every docx block used exactly once and unaltered (after the edits); excerpt literal; headings equal the docx ----
cnt = {k: len(re.findall(r'data-i18n="doc\.%s"' % k, body)) for k in BLOCKS}
bad = {k: v for k, v in cnt.items() if v != 1}
print("docx blocks:", len(BLOCKS), "| data-i18n markers not exactly once:", bad)
if bad: fail.append("markers")
for k in BLOCKS:
    seg = re.search(r'data-i18n="doc\.%s"[^>]*>(.*?)</(?:p|li)>' % k, body, flags=re.S)
    if not (seg and norm(seg.group(1)) == norm(e(paras[k]))):
        print("MISMATCH", k); fail.append("mismatch " + k)
fulln = norm(" ".join(paras[k] for k in BLOCKS))
ex = en["excerpt.text"]
print("excerpt OK" if norm(ex) in fulln else "EXCERPT NOT IN DOCX", "|", norm(ex)[:70])
if norm(ex) not in fulln: fail.append("excerpt")
for key, h in [(f"s{n}", P["paras"][f"s{n}_h"]) for n in range(1, 8)] + [("who", P["paras"]["who_h"]), ("watch", P["paras"]["watch_h"])]:
    ok = norm(en[f"chapter.{key}.title"]) == h
    print(f"heading {key}:", "OK" if ok else f"DIFFERS | {norm(en[f'chapter.{key}.title'])!r} vs {h!r}")
    if not ok: fail.append(f"heading {key}")
assert "[EXT" not in page and "[DB" not in page
print("sources listed:", len(srcs))
if fail:
    print("BUILD CHECK FAILED:", fail); sys.exit(1)
open(f"{PROJ}/index_94.html", "w", encoding="utf-8").write(page)
open(f"{PROJ}/index.html", "w", encoding="utf-8").write(page)   # GitHub Pages serves index.html at the site root
print(len(page), "bytes written")
